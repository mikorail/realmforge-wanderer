func shTalk(g *Game, a *Actor) []Option {
	bd := g.trHere()
	if bd == nil || !bd.Port {
		return nil
	}
	sp := g.sh().Ship
	if a.Role == "shipwright" {
		return g.shWrightTalk(a, bd)
	}
	if a.Title == "sailor" && sp != nil && sp.Port == bd.ID && sp.Crew < sp.K().MaxCrew && sp.Charter == 0 {
		return []Option{{"{{B|Sign on with my ship.}} " + g.cuFormat(10), func() {
			if !g.cuSpend(10) {
				g.talkMenu("\"Bounty first, captain.\"")
				return
			}
			sp.Crew++
			keep := g.Cur.Actors[:0]
			for _, b := range g.Cur.Actors {
				if b != a {
					keep = append(keep, b)
				}
			}
			g.Cur.Actors = keep // walks off to the ship
			g.Mode, g.Talk = "main", nil
			g.Msg(fmt.Sprintf("%s signs on with the %s.", a.Name, sp.Name))
		}}}
	}
	return nil
}

func (g *Game) shWrightTalk(a *Actor, bd *BurgData) []Option {
	st := g.sh()
	sp := st.Ship
	back := func() { g.talkMenu(g.greeting(a)) }
	var out []Option
	out = append(out, Option{"{{B|Show me ships for sale.}}", func() {
		g.Talk = a
		g.Popup = Wrap(fmt.Sprintf("\"These are built on our slips. Crew wages are %.0f a day a head, paid in port.\"", shWage(g.Genre)), 100)
		g.Opts = nil
		for _, k := range g.shOffer(bd) {
			k := k
			price := k.Price * (100 - g.Skills["persuasion"]*5) / 100
			trade := 0
			if sp != nil && sp.Charter == 0 && sp.Port == bd.ID {
				trade = g.shValue(sp)
			}
			label := fmt.Sprintf("{{Y|%s}} {{K|(hull %d, %d km/day, hold %d, crew %d-%d, %d %s)}} — %s", trCap(k.Name), k.Hull, k.Kmd, k.Hold, k.Crew, k.MaxCrew, k.Guns, shGuns(g.Genre), g.cuFormat(maxi(0, price-trade)))
			if trade > 0 {
				label += " {{K|with your ship in trade}}"
			}
			g.Opts = append(g.Opts, Option{label, func() {
				if sp != nil && (sp.Port != bd.ID || sp.Charter > 0) {
					g.talkMenu("\"Bring your own ship in first, or return the charter, and we'll talk.\"")
					return
				}
				if !g.cuSpend(maxi(0, price-trade)) {
					g.talkMenu("\"Ships are not built on promises.\"")
					return
				}
				crew := 0
				hold := []*Item(nil)
				if sp != nil {
					crew, hold = mini(sp.Crew, k.MaxCrew), sp.Hold
				}
				ns := g.shNew(k, bd, crew)
				ns.Hold = hold
				st.Ship = ns
				g.deed("ship", fmt.Sprintf("%s bought the %s %s at %s.", g.P.Name, k.Name, ns.Name, bd.Name), 0, 0)
				g.talkMenu(fmt.Sprintf("\"She's yours: the {{Y|%s}}, a %s. %s Hire hands, take on stores, and mind the weather.\"", ns.Name, k.Name, k.Desc))
			}})
		}
		g.Opts = append(g.Opts, Option{"Never mind.", back})
		g.Sel = 0
	}})
	if sp == nil {
		ks := g.shOffer(bd)
		k := ks[len(ks)/2]
		fee := k.Price / 5
		out = append(out, Option{fmt.Sprintf("{{B|Charter a %s with crew for 30 days.}} — %s", k.Name, g.cuFormat(fee)), func() {
			if !g.cuSpend(fee) {
				g.talkMenu("\"Half up front, half... no, all up front.\"")
				return
			}
			ns := g.shNew(k, bd, k.Crew)
			ns.Charter, ns.Prov = g.Turn+30*DayLen, 20
			st.Ship = ns
			g.talkMenu(fmt.Sprintf("\"The {{Y|%s}} and her crew are yours for thirty days. Wages and stores are in the fee.\"", ns.Name))
		}})
		return out
	}
	if sp.Port != bd.ID {
		return append(out, Option{"Where is my ship?", func() {
			g.talkMenu(fmt.Sprintf("\"The %s? Not in this harbour. Last I heard she lay off %s.\"", sp.Name, g.W.RegionName(sp.At)))
		}})
	}
	k := sp.K()
	if sp.Charter > 0 && g.Turn > sp.Charter {
		st.Ship = nil
		return append(out, Option{"About the charter...", func() {
			g.talkMenu("\"Time's up. The owner's men have taken her back. Charter again any time.\"")
		}})
	}
	if sp.Hull < sp.MaxHull {
		cost := (sp.MaxHull - sp.Hull) * 6
		out = append(out, Option{fmt.Sprintf("Repair the hull (%d/%d). — %s", sp.Hull, sp.MaxHull, g.cuFormat(cost)), func() {
			if !g.cuSpend(cost) {
				g.talkMenu("\"Pitch and timber cost money.\"")
				return
			}
			sp.Hull = sp.MaxHull
			g.tvPass(240)
			g.talkMenu("\"Caulked, patched and tight as a drum.\"")
		}})
	}
	if sp.Charter == 0 {
		perDay := 1 + float64(sp.Crew)/4
		cost := int(math.Ceil(20 * perDay / 2))
		out = append(out, Option{fmt.Sprintf("Take on 20 days of stores (%.0f now). — %s", sp.Prov, g.cuFormat(cost)), func() {
			if !g.cuSpend(cost) {
				g.talkMenu("\"Hardtack isn't free.\"")
				return
			}
			sp.Prov += 20
			g.talkMenu("\"Barrels are going aboard now.\"")
		}})
		if sp.Crew < k.MaxCrew {
			n := mini(4, k.MaxCrew-sp.Crew)
			out = append(out, Option{fmt.Sprintf("Hire %d sailors (%d aboard). — %s", n, sp.Crew, g.cuFormat(15*n)), func() {
				if !g.cuSpend(15 * n) {
					g.talkMenu("\"They want their signing coin.\"")
					return
				}
				sp.Crew += n
				sp.Morale = mini(100, sp.Morale+2)
				g.talkMenu(fmt.Sprintf("\"%d hands, sober-ish. They'll be aboard by the tide.\"", n))
			}})
		}
		if sp.Owed >= 1 {
			out = append(out, Option{fmt.Sprintf("Pay the crew. — %s", g.cuFormat(int(math.Ceil(sp.Owed)))), func() { g.shPayCrew(sp, true); back() }})
		}
		out = append(out, Option{fmt.Sprintf("Sell the %s. — %s", sp.Name, g.cuFormat(g.shValue(sp))), func() {
			g.cuEarn(g.shValue(sp))
			st.Ship = nil
			g.talkMenu("\"A fair price. She'll sail again under another name.\"")
		}})
	}
	out = append(out, Option{"{{G|Set sail.}}", func() { g.Talk = nil; g.shSetSail() }})
	return out
}

func (g *Game) shValue(sp *shShip) int {
	return sp.K().Price * (sp.Hull + sp.MaxHull) / (4 * sp.MaxHull)
}

// shSetSail takes you aboard your moored ship and out to the world map.
func (g *Game) shSetSail() bool {
	sp := g.sh().Ship
	if sp == nil || sp.Aboard {
		return false
	}
	if g.nearHostile() {
		g.Msg("{{R|Not with enemies on the quay!}}")
		return false
	}
	if g.Cur != nil && (g.Cur.Z != 0 || g.W.Idx(g.Cur.WX, g.Cur.WY) != sp.At) {
		g.Msg("Your ship is not here.")
		return false
	}
	g.shBoard(sp)
	g.shArrive(sp.At)
	g.OnWorld, g.Mode = true, "world"
	g.Msg(fmt.Sprintf("You go aboard the {{Y|%s}}. Steer out to sea with the arrows; Z for the ship.", sp.Name))
	return true
}

// ---- zones: shipwrights in every harbour ----

func shZone(g *Game, zn *Zone, _ *Rng) {
	if zn.Kind != "town" || zn.Z != 0 || zn.Burg <= 0 {
		return
	}
	bd := g.W.burgByID[zn.Burg]
	if bd == nil || !bd.Alive || !bd.Port {
		return
	}
	ferry := false
	for _, a := range zn.Actors {
		if a.Role == "ferry" {
			ferry = true
		}
	}
	if !ferry {
		return
	}
	g.trPlace(zn, bd, "shipwright", "shipwright", fmt.Sprintf("The shipwright of %s, who builds, sells, charters and repairs ships.", bd.Name), "")
	for _, a := range zn.Actors {
		if a.Role == "shipwright" {
			a.F = CBrown
		}
	}
}

