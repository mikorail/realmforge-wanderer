// shWorldKey handles keys on the world map while aboard (one hook at the top of keyWorld).
func shWorldKey(g *Game, k string) bool {
	sp := g.sh().Ship
	if sp == nil || !sp.Aboard || g.W.Idx(g.WX, g.WY) != sp.At {
		return false
	}
	switch k {
	case ">", "Enter":
		bd := g.W.burgByID[g.W.Burg[sp.At]]
		if bd != nil && !g.W.IsWater(sp.At) {
			g.shMoor(sp, sp.At, bd.ID)
			g.EnterFromWorld()
			return true
		}
		g.shEnterDeck()
		return true
	case "Escape", "<":
		g.shEnterDeck()
		return true
	case "Z":
		g.shMenu()
		return true
	}
	return false
}

// shEdge: walking off a ship zone goes back to the helm (one hook at the top of crossEdge).
func shEdge(g *Game) bool {
	if g.Cur == nil || g.Cur.Z != shDeckZ {
		return false
	}
	if g.Cur.Key == shBoardKey && g.sh().Fight != nil {
		g.shFlee(true)
		return true
	}
	g.shHelm()
	return true
}

// shHelm returns from the deck to the world map.
func (g *Game) shHelm() {
	sp := g.sh().Ship
	if sp == nil {
		g.Msg("You have no ship.")
		return
	}
	if g.nearHostile() {
		g.Msg("{{R|Not with enemies aboard!}}")
		return
	}
	if g.Cur != nil && g.Cur.Key == shBoardKey {
		g.shClearBoard()
	}
	sp.Aboard = true
	g.shArrive(sp.At)
	g.OnWorld, g.Mode = true, "world"
}

func shMainKey(g *Game) {
	if g.Cur != nil && g.Cur.Z == shDeckZ || g.sh().Ship != nil {
		g.shMenu()
		return
	}
	g.Msg("You have no ship. Shipwrights in port towns sell and charter them.")
}

// shMenu is the ship screen (Z).
func (g *Game) shMenu() {
	st := g.sh()
	sp := st.Ship
	back := "main"
	if g.OnWorld {
		back = "world"
	}
	if st.Fight != nil && g.Cur != nil && g.Cur.Key != shBoardKey {
		g.shFightMenu()
		return
	}
	if sp == nil {
		g.Msg("You have no ship.")
		return
	}
	k := sp.K()
	dir, str := g.shWind(sp.At)
	where := "at anchor off " + g.W.RegionName(sp.At)
	switch {
	case sp.Port > 0:
		where = "moored at " + g.W.burgByID[sp.Port].Name
	case sp.Aboard:
		where = "at sea, " + g.W.RegionName(sp.At)
	}
	lines := []string{
		fmt.Sprintf("{{Y|The %s}}, %s — %s.", sp.Name, k.Name, where),
		fmt.Sprintf("Hull %d/%d · %d km/day in a fair wind · %d %s · hold %d/%d", sp.Hull, sp.MaxHull, k.Kmd, k.Guns, shGuns(g.Genre), len(sp.Hold), k.Hold),
		fmt.Sprintf("Crew %d (+%d companions, needs %d, berths %d) · morale %d · stores %.0f days · wages owed %.0f", sp.Crew, g.shCompanions(), k.Crew, k.MaxCrew, sp.Morale, sp.Prov, sp.Owed),
		"Wind: " + shWindName(dir, str) + ". " + g.shWeather(sp.At).Kind.Name + ".",
	}
	if sp.Charter > 0 {
		lines = append(lines, fmt.Sprintf("{{y|Chartered: %s left.}}", tvDuration(maxi(0, sp.Charter-g.Turn))))
	}
	if k.Engine {
		lines = append(lines, "{{K|Engines: wind barely matters, calms do not stop you.}}")
	} else {
		lines = append(lines, "{{K|Sails: fair winds speed you, headwinds and calms slow you.}}")
	}
	g.Popup = nil
	for _, l := range lines {
		g.Popup = append(g.Popup, Wrap(l, 100)...)
	}
	g.Opts = nil
	add := func(t string, f func()) { g.Opts = append(g.Opts, Option{t, f}) }
	onDeck := g.Cur != nil && g.Cur.Z == shDeckZ
	if sp.Aboard && g.OnWorld {
		add("Walk the deck.", func() { g.shEnterDeck() })
	}
	if onDeck {
		add("Take the helm (world map).", func() { g.shHelm() })
	}
	if sp.Aboard && g.W.IsWater(sp.At) {
		add("Fish over the side (2 hours).", func() { g.shFish() })
		g.Opts = append(g.Opts, g.wrShipOpts()...) // sounding line (wrecks.go)
		for i := range st.Wrecks {
			wr := &st.Wrecks[i]
			if wr.P == sp.At && !wr.Salvaged {
				add("{{C|Dive to the wreck of "+wr.Name+".}}", func() { g.shDive(wr) })
			}
		}
	}
	if !sp.Aboard && sp.Port == 0 && g.Cur != nil && g.Cur.Z == 0 {
		add("Signal the ship (row out).", func() {
			p := g.W.Idx(g.Cur.WX, g.Cur.WY)
			if abs(p%g.W.W-sp.At%g.W.W) > 1 || abs(p/g.W.W-sp.At/g.W.W) > 1 {
				g.shMenuMsg("The ship lies too far off to see your signal.")
				return
			}
			if g.nearHostile() {
				g.shMenuMsg("Not with enemies about.")
				return
			}
			g.shBoard(sp)
			g.shArrive(sp.At)
			g.shEnterDeck()
		})
	}
	if sp.Port > 0 && g.Cur != nil && g.Cur.Z == 0 && g.Cur.Burg == sp.Port {
		add("{{G|Go aboard and set sail.}}", func() { g.shSetSail() })
	}
	if len(sp.Hold) > 0 {
		add(fmt.Sprintf("Unload the hold (%d lots) into your pack.", len(sp.Hold)), func() {
			if sp.Aboard || g.Cur != nil && (g.Cur.Z == shDeckZ || g.Cur.Burg == sp.Port && sp.Port > 0) {
				for _, it := range sp.Hold {
					g.give(it)
				}
				sp.Hold = nil
				g.shMenuMsg("You haul the cargo out of the hold.")
				return
			}
			g.shMenuMsg("The ship is not here.")
		})
	}
	add("Close.", func() { g.Mode = back })
	g.Sel = 0
	st.Title, st.Back = "Ship", back
	g.Mode = "ship"
}

func (g *Game) shMenuMsg(s string) {
	g.Msg(s)
	b := g.sh().Back
	if b == "" {
		b = "main"
	}
	g.Mode = b
}

func shKeys(g *Game, k string) {
	st := g.sh()
	g.keyMenu(k, func() {
		if st.Fight != nil && g.Cur != nil && g.Cur.Key != shBoardKey {
			return // no walking away from a fight at sea
		}
		g.Mode = st.Back
		if g.Mode == "" {
			g.Mode = "main"
		}
	})
}

func shDraw(g *Game) {
	s := g.sc
	if g.OnWorld {
		pop, info := g.Popup, g.wmInfo
		g.drawWorld() // the sea under the menu, not the harbour you left
		g.Popup, g.wmInfo = pop, info
	}
	h := len(g.Popup) + len(g.Opts) + 5
	y0 := maxi(1, (MH-h)/2)
	s.Box(2, y0, SW-4, h, CBrown, g.sh().Title)
	y := y0 + 1
	for _, l := range g.Popup {
		s.TextB(5, y, l, CGray, CBgDark, SW-3)
		y++
	}
	y++
	for i, o := range g.Opts {
		bg := CBgDark
		if i == g.Sel {
			bg = CBgSel
		}
		s.TextB(5, y, fmt.Sprintf("%c) %s", 'a'+i, o.Text), CWhite, bg, SW-3)
		y++
	}
}

// shSide is the sidebar line.
func shSide(g *Game) []string {
	sp := g.sh().Ship
	if sp == nil {
		return nil
	}
	dir, str := g.shWind(sp.At)
	s := fmt.Sprintf("{{y|%s}} hull %d/%d, %.0fd stores", sp.Name, sp.Hull, sp.MaxHull, sp.Prov)
	if sp.Aboard {
		return []string{s, "{{K|Wind " + shWindName(dir, str) + "}}"}
	}
	if sp.Port > 0 {
		return []string{s + " {{K|(moored)}}"}
	}
	return []string{s + " {{K|(at anchor)}}"}
}

// shWorldGlyph marks your ship on the world map (one line in drawWorld).
