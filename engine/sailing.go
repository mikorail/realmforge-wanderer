// shInfo is the world-map cursor's sailing lines (one line in drawWorld).
func (g *Game) shInfo(p int) []string {
	sp := g.sh().Ship
	if sp == nil {
		return nil
	}
	var out []string
	if sp.At == p && !sp.Aboard {
		out = append(out, "{{Y|Your ship, the "+sp.Name+", lies here}}")
	}
	if sp.Aboard && g.W.IsWater(p) {
		dx, dy := sign(p%g.W.W-g.WX), sign(p/g.W.W-g.WY)
		if dx != 0 || dy != 0 {
			out = append(out, fmt.Sprintf("{{K|Sailing %s: %.0f km/day, a leg takes %s}}", shDirNames[shHeading(dx, dy)], g.shSpeed(sp, p, dx, dy), tvDuration(g.shLegMinutes(sp, p, dx, dy))))
		}
		dir, str := g.shWind(p)
		out = append(out, "{{K|Wind "+shWindName(dir, str)+"}}")
	}
	return out
}

// FuzzShip gives the player a ship in a port and puts them aboard (cmd/fuzz).
func (g *Game) FuzzShip(n int) bool {
	w := g.W
	var ports []*BurgData
	for i := range w.Burgs {
		if b := &w.Burgs[i]; b.Alive && b.Port && b.Layer == "surface" {
			ports = append(ports, b)
		}
	}
	if len(ports) == 0 {
		return false
	}
	bd := ports[n%len(ports)]
	g.enterZone(g.GetZone(bd.P%w.W, bd.P/w.W, 1, 1, 0), 40, 12, true)
	g.Mode = "main"
	ks := g.shOffer(bd)
	st := g.sh()
	st.Ship = g.shNew(ks[n%len(ks)], bd, 4)
	st.Ship.Prov = 30
	if !g.shSetSail() {
		return false
	}
	if n%3 == 0 {
		st.Fight = &shFight{Kind: "pirate", Name: "the Fuzz", Hull: 20, MaxHull: 20, Guns: 1, Kmd: 200, Crew: 3, Level: 1, Prize: 10}
		g.shFightMenu()
	}
	return true
}

