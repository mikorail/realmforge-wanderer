func shKindByID(id string) *shKind {
	for i := range shKinds {
		if shKinds[i].ID == id {
			return &shKinds[i]
		}
	}
	return &shKinds[0]
}

// shGuns is what the genre calls a ship's armament.
func shGuns(genre string) string {
	switch genre {
	case "steampunk":
		return "cannon"
	case "dieselpunk":
		return "deck guns"
	case "atompunk":
		return "missile racks"
	case "cyberpunk":
		return "railguns"
	case "biopunk":
		return "spine-launchers"
	case "solarpunk":
		return "water cannon"
	case "wasteland":
		return "harpoon guns"
	}
	return "ballistae"
}

